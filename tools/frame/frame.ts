// Writes src/frame-bridge.ts from frame/bridge.js, run as is by the Node in .nvmrc (`npm run frame`): the bridge's
// text as one string the Worker adds to every saved page (src/page.ts), and its version, the first 12 hex digits of
// the text's SHA-256, which every page's ETag carries, so a changed bridge never ships under an old tag. The Worker's
// bundle holds one module, and the frame's CSP runs only inline scripts, so the bridge travels as text. `--check`
// (in `npm run typecheck`) fails when the file on disk isn't what this would write.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../frame/bridge.js", import.meta.url);
const target = new URL("../../src/frame-bridge.ts", import.meta.url);

/** The generated module for a bridge's text; refused when the text would end the script it is put in early. */
export function generated(bridge: string): string {
  if (/<\/script|<!--/i.test(bridge)) throw new Error("frame/bridge.js must not hold </script or <!--, which would end its script tag");
  const version = createHash("sha256").update(bridge).digest("hex").slice(0, 12);
  return [
    "// Generated by tools/frame/frame.ts from frame/bridge.js (`npm run frame`); never edited by hand. `npm run typecheck`",
    "// fails when it differs from what the tool would write.",
    "",
    "/** The bridge's text, added to every saved page inside a module script (src/page.ts). */",
    `export const BRIDGE = ${JSON.stringify(bridge)};`,
    "",
    "/** The bridge's version: the first 12 hex digits of its text's SHA-256, carried in every page's ETag. */",
    `export const SCRIPT_VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n");
}

const wanted = generated(readFileSync(source, "utf8"));
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    current = "";
  }
  if (current !== wanted) {
    process.stderr.write("src/frame-bridge.ts is not what frame/bridge.js makes: run `npm run frame`\n");
    process.exitCode = 1;
  }
} else writeFileSync(target, wanted);
